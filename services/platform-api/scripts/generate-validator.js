import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// Generate static validation code so Workers never require runtime dynamic evaluation
function generate() {
  const schema = JSON.parse(readFileSync(new URL("../../../packages/contracts/schemas/play-sessions.schema.json", import.meta.url), "utf8"));
  const ajv = new Ajv2020({ strict: true, code: { source: true, esm: true, lines: true } });

  addFormats(ajv);
  ajv.addSchema(schema, "play-sessions");

  let code = standaloneCode(ajv, { validatePlaySessions: "play-sessions" });

  code = code.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)(\.default)?/g, "(ucs2length.default || ucs2length)");
  code = code.replace(/require\("ajv-formats\/dist\/formats"\)\.fullFormats/g, "formats.fullFormats");

  if (code.includes("require(")) {
    throw new Error("Unhandled CommonJS import in generated validator");
  }

  const directory = new URL("../src/generated/", import.meta.url);

  mkdirSync(directory, { recursive: true });
  writeFileSync(new URL("play-sessions.js", directory),
    `// Generated by scripts/generate-validator.js\nimport ucs2length from "ajv/dist/runtime/ucs2length.js";\nimport formats from "ajv-formats/dist/formats.js";\n\n${code}`.replace(/\r\n/g, "\n"));
}

generate();
