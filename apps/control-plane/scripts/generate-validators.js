import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const DESCRIPTOR_SCHEMA_PATH = path.resolve(
  __dirname,
  "../../../contracts/schemas/deployment-artifact-descriptor.schema.json"
);
const GAME_RELEASE_SOURCE_SCHEMA_PATH = path.resolve(
  __dirname,
  "../../../contracts/schemas/game-release-source.schema.json"
);
const OUTPUT_DIR = path.resolve(__dirname, "../lib/generated");
const OUTPUT_FILE = path.resolve(OUTPUT_DIR, "schema-validators.js");

function main() {
  if (!fs.existsSync(DESCRIPTOR_SCHEMA_PATH)) {
    throw new Error(`Descriptor schema not found at: ${DESCRIPTOR_SCHEMA_PATH}`);
  }
  if (!fs.existsSync(GAME_RELEASE_SOURCE_SCHEMA_PATH)) {
    throw new Error(`Game release source schema not found at: ${GAME_RELEASE_SOURCE_SCHEMA_PATH}`);
  }

  const descriptorSchema = JSON.parse(fs.readFileSync(DESCRIPTOR_SCHEMA_PATH, "utf-8"));
  const gameReleaseSourceSchema = JSON.parse(fs.readFileSync(GAME_RELEASE_SOURCE_SCHEMA_PATH, "utf-8"));

  const AjvClass = Ajv2020.default || Ajv2020;
  const ajv = new AjvClass({
    allErrors: true,
    strict: false,
    code: { source: true, esm: true, lines: true },
  });
  const formatFn = addFormats.default || addFormats;
  formatFn(ajv);

  ajv.addSchema(descriptorSchema, "validateDescriptorAjv");
  ajv.addSchema(gameReleaseSourceSchema, "validateGameReleaseSourceAjv");

  const standalone = standaloneCode.default || standaloneCode;
  let code = standalone(ajv, {
    validateDescriptorAjv: "validateDescriptorAjv",
    validateGameReleaseSourceAjv: "validateGameReleaseSourceAjv",
  });

  // Transform CommonJS require calls to ESM imports for browser/worker/bundler compatibility
  const header = `// @ts-nocheck
/* eslint-disable */
/**
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY.
 * Generated by apps/control-plane/scripts/generate-validators.js
 * Source schemas:
 *  - contracts/schemas/deployment-artifact-descriptor.schema.json
 *  - contracts/schemas/game-release-source.schema.json
 */
import ucs2length from "ajv/dist/runtime/ucs2length.js";
import formats from "ajv-formats/dist/formats.js";

`;

  code = code.replace(
    /require\("ajv\/dist\/runtime\/ucs2length"\)(\.default)?/g,
    "(ucs2length.default || ucs2length)"
  );
  code = code.replace(
    /require\("ajv-formats\/dist\/formats"\)\.fullFormats/g,
    "(formats.fullFormats || formats.default?.fullFormats || formats)"
  );

  if (code.includes("require(")) {
    throw new Error("Generated validator code contains unhandled CommonJS require() calls.");
  }

  // Ensure deterministic LF line endings
  const finalCode = (header + code).replace(/\r\n/g, "\n");

  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, finalCode, "utf-8");
  console.log(`Successfully generated standalone validators at: ${OUTPUT_FILE}`);
}

main();
